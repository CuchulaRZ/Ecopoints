-- Ejecutar despues de 01_auth_schema.sql en el mismo esquema de Oracle.
-- REGISTRO_PUNTOS y PROFESOR pertenecen al esquema base de Ecopoints.
-- REGISTRO_PUNTOS debe tener ID_PROFESOR para registrar quien asigno los puntos.

CREATE TABLE COLEGIO_ALUMNO (
    ID_COLEGIO NUMBER NOT NULL,
    ID_ALUMNO  NUMBER NOT NULL,

    CONSTRAINT PK_COLEGIO_ALUMNO PRIMARY KEY (ID_COLEGIO, ID_ALUMNO),
    CONSTRAINT FK_CA_COLEGIO FOREIGN KEY (ID_COLEGIO) REFERENCES COLEGIO(ID_COLEGIO),
    CONSTRAINT FK_CA_ALUMNO FOREIGN KEY (ID_ALUMNO) REFERENCES ALUMNO(ID_ALUMNO)
);
