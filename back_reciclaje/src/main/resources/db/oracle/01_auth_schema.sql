-- Ejecutar despues del script base de Ecopoints.
-- IDENTIFICADOR contiene el codigo del alumno o el usuario del profesor/colegio.

CREATE TABLE USUARIO (
    ID_USUARIO      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    IDENTIFICADOR  VARCHAR2(80) NOT NULL,
    PASSWORD_HASH  VARCHAR2(100) NOT NULL,
    ROL            VARCHAR2(20) NOT NULL,
    ID_ALUMNO      NUMBER,
    ID_COLEGIO     NUMBER,
    ESTADO         CHAR(1) DEFAULT 'A' NOT NULL,
    FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_IDENTIFICADOR UNIQUE (IDENTIFICADOR),
    CONSTRAINT UK_USUARIO_ALUMNO UNIQUE (ID_ALUMNO),
    CONSTRAINT FK_USUARIO_ALUMNO FOREIGN KEY (ID_ALUMNO)
        REFERENCES ALUMNO(ID_ALUMNO),
    CONSTRAINT FK_USUARIO_COLEGIO FOREIGN KEY (ID_COLEGIO)
        REFERENCES COLEGIO(ID_COLEGIO),
    CONSTRAINT CK_USUARIO_ROL CHECK (ROL IN ('ALUMNO', 'PROFESOR', 'INSTITUCION', 'ADMIN')),
    CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('A', 'I')),
    CONSTRAINT CK_USUARIO_ASOCIACION CHECK (
        (ROL = 'ALUMNO' AND ID_ALUMNO IS NOT NULL AND ID_COLEGIO IS NULL)
        OR (ROL IN ('PROFESOR', 'INSTITUCION')
            AND ID_ALUMNO IS NULL AND ID_COLEGIO IS NOT NULL)
        OR (ROL = 'ADMIN' AND ID_ALUMNO IS NULL AND ID_COLEGIO IS NULL)
    )
);

CREATE INDEX IDX_USUARIO_COLEGIO ON USUARIO(ID_COLEGIO);
