package backend_r.reciclaje.dashboard;

import static org.springframework.security.test.web.servlet.request.SecurityMockMvcRequestPostProcessors.csrf;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import backend_r.reciclaje.domain.ColegioRepository;
import backend_r.reciclaje.domain.Profesor;
import backend_r.reciclaje.domain.ProfesorRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mock.web.MockHttpSession;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;

@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
class DashboardControllerTests {
    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private JdbcTemplate jdbc;

    @Autowired
    private ColegioRepository colegios;

    @Autowired
    private ProfesorRepository profesores;

    @Autowired
    private PasswordEncoder passwordEncoder;

    @BeforeEach
    void createDashboardTables() {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS COLEGIO_ALUMNO (
                    ID_COLEGIO BIGINT NOT NULL,
                    ID_ALUMNO BIGINT NOT NULL,
                    PRIMARY KEY (ID_COLEGIO, ID_ALUMNO)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS REGISTRO_PUNTOS (
                    ID_REGISTRO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ID_ALUMNO BIGINT NOT NULL,
                    ID_ACTIVIDAD BIGINT,
                    PUNTOS INTEGER NOT NULL,
                    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    OBSERVACION VARCHAR(300),
                    ID_PROFESOR BIGINT NOT NULL REFERENCES PROFESOR(ID_PROFESOR)
                )
                """);
    }

    @Test
    void teacherCanRegisterStudentAndAwardPointsVisibleInStudentDashboard() throws Exception {
        long suffix = Math.abs(System.nanoTime());
        long collegeId = suffix;
        jdbc.update("INSERT INTO COLEGIO (ID_COLEGIO, NOMBRE) VALUES (?, ?)", collegeId, "Colegio Verde");
        Profesor teacher = profesores.saveAndFlush(new Profesor(
                colegios.findById(collegeId).orElseThrow(),
                "Patricia",
                "Verde",
                "teacher-" + suffix + "@example.test",
                passwordEncoder.encode("teacher-test-password-123"),
                321L));

        MockHttpSession teacherSession = loginById(teacher.getId().toString());
        mockMvc.perform(post("/api/docente/alumnos")
                        .session(teacherSession)
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"nombre":"Ana","apellido":"Verde"}
                                """))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.nombreCompleto").value("Ana Verde"));

        long studentId = jdbc.queryForObject(
                "SELECT ID_ALUMNO FROM COLEGIO_ALUMNO WHERE ID_COLEGIO = ?",
                Long.class,
                collegeId);
        org.assertj.core.api.Assertions.assertThat(studentId).isBetween(10_000_000L, 99_999_999L);
        org.assertj.core.api.Assertions.assertThat(jdbc.queryForObject(
                "SELECT ID_SALON FROM ALUMNO WHERE ID_ALUMNO = ?",
                Long.class,
                studentId)).isEqualTo(321L);

        mockMvc.perform(get("/api/docente/alumnos").session(teacherSession))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[0].puntosTotal").value(0));

        mockMvc.perform(post("/api/docente/puntos")
                        .session(teacherSession)
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"alumnoId":%d,"puntos":15,"motivo":"Separó los residuos"}
                                """.formatted(studentId)))
                .andExpect(status().isOk());

        mockMvc.perform(get("/api/docente/alumnos/ganador-30-dias").session(teacherSession))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.alumnoId").value(studentId))
                .andExpect(jsonPath("$.nombreCompleto").value("Ana Verde"))
                .andExpect(jsonPath("$.puntosTotal").value(15));

        MockHttpSession studentSession = loginById(Long.toString(studentId));
        mockMvc.perform(get("/api/alumno/puntos").session(studentSession))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.puntosTotal").value(15))
                .andExpect(jsonPath("$.movimientos[0].puntos").value(15))
                .andExpect(jsonPath("$.movimientos[0].motivo").value("Separó los residuos"))
                .andExpect(jsonPath("$.movimientos[0].fecha").isNotEmpty());
        org.assertj.core.api.Assertions.assertThat(jdbc.queryForObject(
                "SELECT ID_PROFESOR FROM REGISTRO_PUNTOS WHERE ID_ALUMNO = ?",
                Long.class,
                studentId)).isEqualTo(teacher.getId());

        mockMvc.perform(post("/api/docente/puntos")
                        .session(studentSession)
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"alumnoId":%d,"puntos":100,"motivo":"Acceso no autorizado"}
                                """.formatted(studentId)))
                .andExpect(status().isForbidden());
    }

    @Test
    void studentCreatedDirectlyInAlumnoCanLogInAndReadDashboard() throws Exception {
        long studentId = System.nanoTime();
        jdbc.update("INSERT INTO ALUMNO (ID_ALUMNO, NOMBRE, APELLIDO, ID_SALON) VALUES (?, ?, ?, ?)",
                studentId, "Pepito", "Palote", 321L);

        MockHttpSession studentSession = loginById(Long.toString(studentId));
        mockMvc.perform(get("/api/alumno/puntos").session(studentSession))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.alumnoId").value(studentId))
                .andExpect(jsonPath("$.nombreCompleto").value("Pepito Palote"))
                .andExpect(jsonPath("$.puntosTotal").value(0))
                .andExpect(jsonPath("$.movimientos").isArray())
                .andExpect(jsonPath("$.movimientos").isEmpty());
    }

    private MockHttpSession loginById(String identifier) throws Exception {
        MvcResult login = mockMvc.perform(post("/api/auth/login-id")
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"identificador":"%s"}
                                """.formatted(identifier)))
                .andExpect(status().isOk())
                .andReturn();
        return (MockHttpSession) login.getRequest().getSession(false);
    }
}
